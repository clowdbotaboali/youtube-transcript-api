export async function processWithGroq(transcript, type = 'all') {
  try {
    const apiKey = process.env.GROQ_API_KEY;
    if (!apiKey) {
      throw new Error('GROQ API key is missing');
    }

    const groq = new Groq({ apiKey });
    const prompt = prompts[type] ? prompts[type](transcript) : prompts.all(transcript);

    const completion = await groq.chat.completions.create({
      messages: [
        {
          role: 'system',
          content: 'أنت خبير في تحليل المحتوى التعليمي واستخراج التفاصيل الدقيقة. مهمتك تحويل الفيديوهات إلى أدلة عمل قابلة للتنفيذ بدقة شديدة، بدون تلخيص أو حذف تفاصيل.'
        },
        {
          role: 'user',
          content: prompt
        }
      ],
      model: 'llama-3.3-70b-versatile',
      temperature: 0.3,
      max_tokens: 32000
    });

    return completion.choices[0]?.message?.content || '';
  } catch (error) {
    console.error('Groq API Error:', error);
    throw new Error('فشل في معالجة النص بالذكاء الاصطناعي: ' + error.message);
  }
}
